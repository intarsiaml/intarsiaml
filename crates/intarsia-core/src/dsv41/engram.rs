//! DeepSeek-V4.1 Engram: the n-gram hash (host side) and the off-device table tier interface.
//!
//! The official code (`inference/engram.py`, `model.py` `ParallelEngramEmbedding` / `Engram`, MIT, DeepSeek) hashes the
//! last `max_ngram_size` compressed token ids of every position into `(max_ngram_size - 1) * n_heads` row indices of a
//! per-layer FP8 table (`[~384M, 256]` e4m3 plus `[~384M, 8]` E8M0 scales per layer, 203 GB for the two Engram layers).
//! The row addresses depend on token ids only, never on hidden state, so they are known when a pass starts: the engine
//! hashes on the host ([`NgramHasher`]) and issues the row fetch to an [`EngramTier`] the moment the token ids are known
//! (scope doc variant A2), then uploads the rows for `Op::EngramGather` + `Op::EngramMerge`.
//!
//! Not here (Engram lane): the compressed token map (`build_compressed_token_map`, a tokenizer normaliser pass that must
//! give exactly `engram_compressed_vocab_size` = 99,092 ids) and the NVMe `io_uring` tier with its hot rows.

use crate::error::{Error, Result};
use std::collections::HashMap;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Mutex;

/// Elements per E8M0 scale of a table row.
pub const SCALE_BLOCK: usize = 32;

/// Bucket layout of the hash tables (`EngramLayout`): every `(n-gram size, head)` owns a prime-sized range of the layer's
/// table, primes drawn in order from `engram_vocab_size` upwards and never reused.
#[derive(Clone, Debug, PartialEq)]
pub struct EngramLayout {
    pub layer_ids: Vec<usize>,
    pub max_ngram: usize,
    pub n_heads: usize,
    pub head_dim: usize,
    /// Unpadded table rows per Engram layer (`engram_num_embeddings`).
    pub rows: Vec<u64>,
    /// `[layer][n-gram size - 2][head]` bucket modulus.
    pub primes: Vec<Vec<Vec<u64>>>,
}

fn is_prime(n: u64) -> bool {
    if n < 2 {
        return false;
    }
    if n % 2 == 0 {
        return n == 2;
    }
    let mut f = 3u64;
    while f * f <= n {
        if n % f == 0 {
            return false;
        }
        f += 2;
    }
    true
}

impl EngramLayout {
    /// From the config fields (`Dsv41Config`): the primes are derived, then checked against the table sizes the
    /// checkpoint declares (each layer's rows are the sum of its primes).
    pub fn new(layer_ids: &[usize], rows: &[u64], max_ngram: usize, n_heads: usize, head_dim: usize, vocab: u64) -> Result<EngramLayout> {
        if layer_ids.len() != rows.len() || max_ngram < 2 || n_heads == 0 || head_dim % SCALE_BLOCK != 0 {
            return Err(Error::model(format!(
                "engram: {} layers / {} table sizes, max_ngram {max_ngram}, {n_heads} heads, head_dim {head_dim}",
                layer_ids.len(),
                rows.len()
            )));
        }
        let mut seen = std::collections::HashSet::new();
        let mut primes = Vec::new();
        for _ in layer_ids {
            let mut per_ngram = Vec::new();
            for _ in 0..max_ngram - 1 {
                let (mut sizes, mut cur) = (Vec::new(), vocab - 1);
                for _ in 0..n_heads {
                    cur += 1;
                    while !is_prime(cur) || seen.contains(&cur) {
                        cur += 1;
                    }
                    seen.insert(cur);
                    sizes.push(cur);
                }
                per_ngram.push(sizes);
            }
            primes.push(per_ngram);
        }
        let l = EngramLayout { layer_ids: layer_ids.to_vec(), max_ngram, n_heads, head_dim, rows: rows.to_vec(), primes };
        for (i, &r) in rows.iter().enumerate() {
            let sum: u64 = l.primes[i].iter().flatten().sum();
            if sum != r {
                return Err(Error::model(format!("engram layer {}: table rows {r} != sum of its bucket primes {sum}", layer_ids[i])));
            }
        }
        Ok(l)
    }

    /// Hash columns per position and layer (`(max_ngram - 1) * n_heads`, 24).
    pub fn cols(&self) -> usize {
        (self.max_ngram - 1) * self.n_heads
    }
}

/// The host-side hash of `NgramHashState.forward`.
#[derive(Clone, Debug)]
pub struct NgramHasher {
    pub layout: EngramLayout,
    /// `[layer][lookback]` odd 64-bit multipliers (`compute_hash_multipliers`: numpy `default_rng(10007 * layer_id)`,
    /// generated by `tools/gen_dsv41_engram_params.py`, not re-derived here).
    pub multipliers: Vec<Vec<i64>>,
    /// Compressed id of `engram_pad_token_id` (`token_map[2]`): fills the n-gram slots before the sequence start.
    pub pad_id: i64,
}

/// A compressed token id that takes part in no n-gram (an image span): look-back stops at it.
pub const DEAD: i64 = -1;

impl NgramHasher {
    /// Row indices for positions `start .. start + t` of a sequence whose compressed ids are `compressed[..start + t]`
    /// (the whole history: the hash reads up to `max_ngram - 1` earlier ids, so a chunked prefill, a decode step and a
    /// truncated sequence all hash from `SequenceState::tokens`). Returns `[t][layer][cols]`, flattened.
    pub fn hash(&self, compressed: &[i64], start: usize, t: usize) -> Result<Vec<u32>> {
        let l = &self.layout;
        if compressed.len() < start + t || self.multipliers.len() != l.layer_ids.len() || self.multipliers.iter().any(|m| m.len() != l.max_ngram) {
            return Err(Error::invalid("engram hash: history shorter than the chunk, or multipliers do not match the layout"));
        }
        let mut out = Vec::with_capacity(t * l.layer_ids.len() * l.cols());
        for pos in start..start + t {
            let mut toks = Vec::with_capacity(l.max_ngram);
            let mut blocked = false;
            for shift in 0..l.max_ngram {
                let src = compressed[pos.saturating_sub(shift)];
                blocked = blocked || pos < shift || src == DEAD;
                toks.push(if blocked { self.pad_id } else { src });
            }
            for (li, m) in self.multipliers.iter().enumerate() {
                let mut rolling = toks[0].wrapping_mul(m[0]);
                let mut offset = 0u64;
                for i in 1..l.max_ngram {
                    rolling ^= toks[i].wrapping_mul(m[i]);
                    for &p in &l.primes[li][i - 1] {
                        out.push((rolling.rem_euclid(p as i64) as u64 + offset) as u32);
                        offset += p;
                    }
                }
            }
        }
        Ok(out)
    }
}

/// A tensor-parallel rank's share of every table: rows `rank * part .. min(rows, (rank + 1) * part)`, `part =
/// ceil(rows / world)` (`ParallelEngramEmbedding`); rows outside it read as zero and the ranks' results are summed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct EngramShard {
    pub rank: usize,
    pub world: usize,
}

impl EngramShard {
    pub fn range(&self, rows: u64) -> std::ops::Range<u64> {
        let part = rows.div_ceil(self.world.max(1) as u64);
        let lo = (self.rank as u64 * part).min(rows);
        lo..(lo + part).min(rows)
    }
}

/// Handle of an issued fetch.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct EngramTicket(pub u64);

/// Where the Engram tables live (host RAM, local NVMe, ...). The engine calls [`EngramTier::issue`] as soon as a pass's token
/// ids are known and [`EngramTier::wait`] right before the rows are uploaded, so the fetch overlaps the layers before the
/// first Engram layer (and graph replays never wait on IO inside a kernel). Where the E8M0 scales are kept (resident
/// array, or packed next to each row as 264 B records) is the tier's business: `wait` hands out both.
pub trait EngramTier: Send + Sync {
    /// The bucket layout the tables were built for.
    fn layout(&self) -> &EngramLayout;
    /// The share of the rows this tier serves.
    fn shard(&self) -> EngramShard;
    /// Start fetching `rows` (absolute row indices of Engram layer `layer`, an index into `layout().layer_ids`). Must not block
    /// on IO.
    fn issue(&self, layer: usize, rows: &[u32]) -> Result<EngramTicket>;
    /// Block until the fetch is complete, then write its rows in request order: `payload` `[n, head_dim]` e4m3 bytes and
    /// `scales` `[n, head_dim / 32]` E8M0 bytes. A row outside [`EngramTier::shard`] comes back as zero payload (any scale).
    fn wait(&self, ticket: EngramTicket, payload: &mut [u8], scales: &mut [u8]) -> Result<()>;
}

/// An in-memory [`EngramTier`] holding its shard's rows (tests, and small synthetic tables).
pub struct MemEngramTier {
    layout: EngramLayout,
    shard: EngramShard,
    /// Per layer: the shard's payload rows `[n, head_dim]` and scales `[n, head_dim / 32]`.
    payload: Vec<Vec<u8>>,
    scales: Vec<Vec<u8>>,
    next: AtomicU64,
    pending: Mutex<HashMap<u64, (usize, Vec<u32>)>>,
}

impl MemEngramTier {
    /// `payload[l]` / `scales[l]` hold exactly the rows of `shard.range(layout.rows[l])`.
    pub fn new(layout: EngramLayout, shard: EngramShard, payload: Vec<Vec<u8>>, scales: Vec<Vec<u8>>) -> Result<MemEngramTier> {
        let (dh, sb) = (layout.head_dim, layout.head_dim / SCALE_BLOCK);
        for (l, &rows) in layout.rows.iter().enumerate() {
            let n = (shard.range(rows).end - shard.range(rows).start) as usize;
            if payload.get(l).map(Vec::len) != Some(n * dh) || scales.get(l).map(Vec::len) != Some(n * sb) {
                return Err(Error::invalid(format!("engram tier layer {l}: need {n} rows of {dh} payload and {sb} scale bytes")));
            }
        }
        Ok(MemEngramTier { layout, shard, payload, scales, next: AtomicU64::new(1), pending: Mutex::new(HashMap::new()) })
    }
}

impl EngramTier for MemEngramTier {
    fn layout(&self) -> &EngramLayout {
        &self.layout
    }
    fn shard(&self) -> EngramShard {
        self.shard
    }
    fn issue(&self, layer: usize, rows: &[u32]) -> Result<EngramTicket> {
        if layer >= self.layout.rows.len() {
            return Err(Error::invalid(format!("engram tier: layer {layer} of {}", self.layout.rows.len())));
        }
        if let Some(&r) = rows.iter().find(|&&r| r as u64 >= self.layout.rows[layer]) {
            return Err(Error::invalid(format!("engram tier: row {r} >= {} rows", self.layout.rows[layer])));
        }
        let id = self.next.fetch_add(1, Ordering::Relaxed);
        self.pending.lock().unwrap().insert(id, (layer, rows.to_vec()));
        Ok(EngramTicket(id))
    }
    fn wait(&self, ticket: EngramTicket, payload: &mut [u8], scales: &mut [u8]) -> Result<()> {
        let (layer, rows) = self.pending.lock().unwrap().remove(&ticket.0).ok_or_else(|| Error::invalid("engram tier: unknown ticket"))?;
        let (dh, sb) = (self.layout.head_dim, self.layout.head_dim / SCALE_BLOCK);
        if payload.len() != rows.len() * dh || scales.len() != rows.len() * sb {
            return Err(Error::invalid("engram tier: output buffers do not match the request"));
        }
        let range = self.shard.range(self.layout.rows[layer]);
        for (j, &r) in rows.iter().enumerate() {
            let (p, s) = (&mut payload[j * dh..(j + 1) * dh], &mut scales[j * sb..(j + 1) * sb]);
            if range.contains(&(r as u64)) {
                let i = (r as u64 - range.start) as usize;
                p.copy_from_slice(&self.payload[layer][i * dh..(i + 1) * dh]);
                s.copy_from_slice(&self.scales[layer][i * sb..(i + 1) * sb]);
            } else {
                p.fill(0);
                s.fill(127);
            }
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> serde_json::Value {
        serde_json::from_str(include_str!("engram_fixture.json")).unwrap()
    }

    fn real_layout() -> EngramLayout {
        EngramLayout::new(&[1, 14], &[384_006_168, 384_016_682], 4, 8, 256, 16_000_000).unwrap()
    }

    #[test]
    fn layout_primes_match_the_official_layout_and_table_sizes() {
        let l = real_layout();
        let want: Vec<Vec<Vec<u64>>> = serde_json::from_value(fixture()["primes"].clone()).unwrap();
        assert_eq!(l.primes, want);
        assert_eq!(l.cols(), 24);
        assert!(EngramLayout::new(&[1, 14], &[384_006_168, 1], 4, 8, 256, 16_000_000).is_err());
    }

    #[test]
    fn hash_matches_the_official_ngram_hash() {
        let f = fixture();
        let h = NgramHasher {
            layout: real_layout(),
            multipliers: serde_json::from_value(f["multipliers"].clone()).unwrap(),
            pad_id: f["pad_id"].as_i64().unwrap(),
        };
        let seq: Vec<i64> = serde_json::from_value(f["compressed"].clone()).unwrap();
        let want: Vec<Vec<Vec<u32>>> = serde_json::from_value(f["hashes"].clone()).unwrap();
        let flat: Vec<u32> = want.iter().flatten().flatten().copied().collect();
        assert_eq!(h.hash(&seq, 0, seq.len()).unwrap(), flat);
        // chunked: any split hashes the same rows (the look-back reads the history)
        let n = 2 * 24;
        assert_eq!(h.hash(&seq, 3, 4).unwrap(), flat[3 * n..7 * n]);
    }

    #[test]
    fn mem_tier_serves_its_shard_and_zeroes_the_rest() {
        let layout = EngramLayout { layer_ids: vec![1], max_ngram: 2, n_heads: 1, head_dim: 64, rows: vec![10], primes: vec![vec![vec![10]]] };
        let shard = EngramShard { rank: 1, world: 2 };
        assert_eq!(shard.range(10), 5..10);
        let payload: Vec<u8> = (0..5 * 64).map(|i| (i % 251) as u8).collect();
        let scales: Vec<u8> = (0..5 * 2).map(|i| 100 + i as u8).collect();
        let t = MemEngramTier::new(layout, shard, vec![payload.clone()], vec![scales.clone()]).unwrap();
        let tk = t.issue(0, &[7, 2, 9]).unwrap();
        let (mut p, mut s) = (vec![1u8; 3 * 64], vec![0u8; 3 * 2]);
        t.wait(tk, &mut p, &mut s).unwrap();
        assert_eq!(&p[..64], &payload[2 * 64..3 * 64]);
        assert!(p[64..128].iter().all(|&b| b == 0));
        assert_eq!(&s[4..6], &scales[4 * 2..5 * 2]);
        assert!(t.wait(tk, &mut p, &mut s).is_err(), "a ticket is consumed by its wait");
        assert!(t.issue(0, &[10]).is_err());
    }
}

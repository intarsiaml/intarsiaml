#[derive(Default)]
struct Mock {
    reqs: Mutex<Vec<GenRequest>>,
    templated: Mutex<Vec<(Vec<Value>, ChatOpts)>>,
    /// When set, generate slowly and forever so cancellation can be observed.
    slow: bool,
    cancelled: Arc<AtomicBool>,
    /// Engine reports itself failed.
    fail: bool,
    /// Scripted generation: token events, `completion_tokens`, finish reason (overrides the canned one).
    script: Option<(Vec<(u32, &'static str)>, usize, FinishReason)>,
    /// Finish with this stop sequence.
    stop_seq: Option<String>,
    /// Telemetry overrides.
    busy: (u32, u32),
    /// `submit` refuses with the engine's own queue-full error.
    queue_full: bool,
    /// The engine dies after this many tokens: the stream ends with an `Error` event instead of `Done`.
    die_after: Option<usize>,
    /// Structured output: a byte-level `tokenizer.json` (token 0 = EOS, 256 = `<tool_call>`, 257 = `</tool_call>`),
    /// hermes tool format, 512-token context; a constrained request is generated by [`constrained_gen`].
    structured: bool,
    /// What the mock "model" wants to say under a constraint (it says it where the mask lets it).
    want: Option<&'static str>,
}

const OPEN_TAG: &str = "<tool_call>";
const CLOSE_TAG: &str = "</tool_call>";

/// Byte tokens, plus the two hermes tags as single tokens.
fn mock_tokenize(text: &str) -> Vec<u32> {
    let mut out = Vec::new();
    let mut rest = text;
    while !rest.is_empty() {
        if let Some(r) = rest.strip_prefix(OPEN_TAG) {
            out.push(256);
            rest = r;
        } else if let Some(r) = rest.strip_prefix(CLOSE_TAG) {
            out.push(257);
            rest = r;
        } else {
            out.push(rest.as_bytes()[0] as u32);
            rest = &rest[1..];
        }
    }
    out
}

fn mock_bytes(id: u32) -> Vec<u8> {
    match id {
        256 => OPEN_TAG.as_bytes().to_vec(),
        257 => CLOSE_TAG.as_bytes().to_vec(),
        0 => Vec::new(),
        b => vec![b as u8],
    }
}

/// `tokenizer.json` of the structured mock (byte fallback decoder, `<0xNN>` byte tokens).
fn mock_tokenizer_json() -> String {
    let mut vocab = serde_json::Map::new();
    for b in 0..256 {
        vocab.insert(format!("<0x{b:02X}>"), json!(b));
    }
    vocab.insert(OPEN_TAG.into(), json!(256));
    vocab.insert(CLOSE_TAG.into(), json!(257));
    json!({
        "added_tokens": [
            {"id": 0, "content": "<eos>", "special": true},
            {"id": 256, "content": OPEN_TAG, "special": false},
            {"id": 257, "content": CLOSE_TAG, "special": false}
        ],
        "decoder": {"type": "Sequence", "decoders": [{"type": "ByteFallback"}]},
        "model": {"type": "BPE", "vocab": vocab}
    })
    .to_string()
}

/// Generate under `req.constraint` as the engine does (mask, pick, stop on EOS, commit): the "model" says `want`
/// where the mask allows it, else it closes what it can (EOS, `"`, `}`, `]`), else says `1`, else the lowest allowed
/// token.
fn constrained_gen(req: &GenRequest, want: &str) -> (Vec<(u32, String)>, usize, FinishReason) {
    let mut c = req.constraint.as_ref().unwrap().start().unwrap();
    let want = mock_tokenize(want);
    let mut out = Vec::new();
    for step in 0..req.max_tokens {
        let pick = if c.active() {
            let m = c.compute_mask().unwrap();
            let pref = want.get(step).copied().into_iter().chain([0, b'"' as u32, b'}' as u32, b']' as u32, b'1' as u32]);
            match pref.clone().find(|&t| m.allows(t)) {
                Some(t) => t,
                None => (0..258).find(|&t| m.allows(t)).expect("mask allows something"),
            }
        } else {
            want.get(step).copied().unwrap_or(0)
        };
        if pick == 0 {
            return (out, step + 1, FinishReason::Stop);
        }
        c.commit(pick).unwrap();
        out.push((pick, String::from_utf8(mock_bytes(pick)).unwrap()));
    }
    let n = out.len();
    (out, n, FinishReason::Length)
}

impl Engine for Mock {
    fn info(&self) -> ModelInfo {
        ModelInfo {
            id: "mock-model".into(),
            family: "mock".into(),
            backend: "cpu".into(),
            device: "test".into(),
            arch: "x".into(),
            n_layers: 1,
            hidden: 1,
            vocab: if self.structured { 258 } else { 256 },
            n_heads: 1,
            n_kv_heads: 1,
            head_dim: 1,
            max_position_embeddings: 64,
            context_len: if self.structured { 512 } else { 64 },
            act_dtype: "bf16".into(),
            kv_dtype: "bf16".into(),
            weights_bytes: 10,
            eos_ids: vec![0],
            has_chat_template: true,
            reasoning_parser: None,
            tool_parser: self.structured.then(|| "hermes".into()),
            memory_plan: MemoryPlan {
                device: "test".into(),
                total_bytes: 0,
                free_bytes: 0,
                weights_bytes: 0,
                workspace_bytes: 0,
                kv_bytes_per_token: 0,
                kv_fraction: 0.5,
                kv_budget_bytes: 0,
                kv_cap_tokens: 64,
                kv_total_bytes: 0,
                notes: vec![],
            },
        }
    }
    fn tokenize(&self, text: &str, _add_special: bool) -> Result<Vec<u32>> {
        if self.structured {
            return Ok(mock_tokenize(text));
        }
        Ok(text.bytes().map(|b| b as u32).collect())
    }
    fn tokenizer_json(&self) -> Option<String> {
        self.structured.then(mock_tokenizer_json)
    }
    fn detokenize(&self, ids: &[u32]) -> Result<String> {
        Ok(ids.iter().map(|i| *i as u8 as char).collect())
    }
    fn apply_chat_template(&self, messages: &[Value], opts: &ChatOpts) -> Result<String> {
        self.templated.lock().unwrap().push((messages.to_vec(), opts.clone()));
        let mut s = String::new();
        for m in messages {
            // The server must hand over plain-string content.
            let c = m["content"].as_str().expect("content must be a string");
            s.push_str(&format!("{}:{}\n", m["role"].as_str().unwrap(), c));
        }
        s.push_str("assistant:");
        Ok(s)
    }
    fn submit(&self, req: GenRequest) -> Result<Receiver<GenEvent>> {
        if self.queue_full {
            return Err(intarsia_core::Error::QueueFull(8));
        }
        let (tx, rx) = channel();
        let plen = req.prompt.len();
        let max = req.max_tokens;
        let constrained = req.constraint.is_some().then(|| constrained_gen(&req, self.want.unwrap_or("")));
        self.reqs.lock().unwrap().push(req);
        let slow = self.slow;
        let die_after = self.die_after;
        let stop_seq = self.stop_seq.clone();
        let cancelled = self.cancelled.clone();
        let script = self.script.clone().or(constrained.map(|(toks, n, f)| {
            let toks: Vec<(u32, &'static str)> =
                toks.into_iter().map(|(i, t)| (i, &*Box::leak(t.into_boxed_str()))).collect();
            (toks, n, f)
        }));
        std::thread::spawn(move || {
            if let Some((toks, completion_tokens, finish_reason)) = script {
                for (id, text) in toks {
                    tx.send(GenEvent::Token { id, text: text.to_string() }).ok();
                }
                tx.send(GenEvent::Done {
                    finish_reason,
                    stop_sequence: None,
                    prompt_tokens: plen,
                    completion_tokens,
                    cached_tokens: 0,
                    prefill_ms: 1.0,
                    decode_ms: 1.0,
                    prefill_chunk: None,
                })
                .ok();
                return;
            }
            if let Some(n) = die_after {
                for _ in 0..n {
                    tx.send(GenEvent::Token { id: 65, text: "x".into() }).ok();
                }
                tx.send(GenEvent::Error { message: "worker panicked: boom".into() }).ok();
                return;
            }
            if slow {
                loop {
                    std::thread::sleep(std::time::Duration::from_millis(5));
                    if tx.send(GenEvent::Token { id: 65, text: "x".into() }).is_err() {
                        cancelled.store(true, Ordering::SeqCst);
                        return;
                    }
                }
            }
            let n = max.min(2);
            let parts = ["Hel", "lo"];
            for p in parts.iter().take(n) {
                tx.send(GenEvent::Token { id: 65, text: p.to_string() }).ok();
                tx.send(GenEvent::Token { id: 65, text: String::new() }).ok();
            }
            let finish = if max < 2 { FinishReason::Length } else { FinishReason::Stop };
            tx.send(GenEvent::Done {
                finish_reason: finish,
                stop_sequence: stop_seq,
                prompt_tokens: plen,
                completion_tokens: n,
                cached_tokens: 3,
                prefill_ms: 20.0,
                decode_ms: 10.0,
                prefill_chunk: None,
            })
            .ok();
        });
        Ok(rx)
    }
    fn forward_logits_each(&self, _ids: &[u32], _cb: &mut dyn FnMut(usize, &[f32]) -> Result<()>) -> Result<()> {
        Ok(())
    }
    fn failed(&self) -> Option<String> {
        self.failed_hook()
    }
    fn plan(&self) -> Value {
        json!({"model": "mock-model", "layers": [], "ops": []})
    }
    fn telemetry(&self) -> TelemetrySnapshot {
        let mut t =
            TelemetrySnapshot { steps_total: 42, schema_version: 1, model: "mock-model".into(), ..Default::default() };
        t.running = self.busy.0;
        t.waiting = self.busy.1;
        t.prompt_tokens_total = 7;
        t.generation_tokens_total = 9;
        t.cached_tokens_total = 3;
        t.kv_used_bytes = 100;
        t.graph_replays = 11;
        t.graph_captures = 2;
        t.decode_eager_steps = 5;
        t.decode_profiled_steps = 3;
        t.kv_total_bytes = 1000;
        t.finished.insert("stop".into(), 2);
        t.ops.insert("matmul".into(), OpStat { calls: 5, timed_calls: 5, time_ms: 1500.0 });
        t
    }
}

impl Mock {
    fn failed_hook(&self) -> Option<String> {
        self.fail.then(|| "worker panicked: boom".to_string())
    }
}

fn app_with(mock: Arc<Mock>) -> Router {
    intarsia_server::router(mock, None)
}

fn app() -> (Router, Arc<Mock>) {
    let m = Arc::new(Mock::default());
    (app_with(m.clone()), m)
}

async fn call(app: &Router, method: &str, uri: &str, body: Option<Value>) -> (StatusCode, String, String) {
    let req = Request::builder()
        .method(method)
        .uri(uri)
        .header("content-type", "application/json")
        .body(match body {
            Some(b) => Body::from(b.to_string()),
            None => Body::empty(),
        })
        .unwrap();
    let resp = app.clone().oneshot(req).await.unwrap();
    let status = resp.status();
    let ct = resp.headers().get("content-type").map(|v| v.to_str().unwrap().to_string()).unwrap_or_default();
    let bytes = resp.into_body().collect().await.unwrap().to_bytes();
    (status, ct, String::from_utf8(bytes.to_vec()).unwrap())
}

fn sse_data(body: &str) -> Vec<String> {
    body.lines().filter_map(|l| l.strip_prefix("data: ")).map(String::from).collect()
}

fn sse_events(body: &str) -> Vec<(String, Value)> {
    let mut out = Vec::new();
    let mut name = String::new();
    for l in body.lines() {
        if let Some(n) = l.strip_prefix("event: ") {
            name = n.to_string();
        } else if let Some(d) = l.strip_prefix("data: ") {
            out.push((std::mem::take(&mut name), serde_json::from_str(d).unwrap()));
        }
    }
    out
}

#[tokio::test]
async fn chat_non_stream() {
    let (app, mock) = app();
    let (st, _, body) = call(
        &app,
        "POST",
        "/v1/chat/completions",
        Some(json!({
            "model": "whatever",
            "messages": [{"role": "system", "content": "be nice"},
                         {"role": "user", "content": [{"type": "text", "text": "hi "}, {"type": "text", "text": "there"}]}],
            "max_tokens": 50, "max_completion_tokens": 9, "min_tokens": 1, "ignore_eos": true,
            "temperature": 0.5, "top_p": 0.9, "top_k": 7, "seed": 11, "stop": ["END", "STOP"],
            "chat_template_kwargs": {"enable_thinking": false, "foo": 1}
        })),
    )
    .await;
    assert_eq!(st, StatusCode::OK, "{body}");
    let v: Value = serde_json::from_str(&body).unwrap();
    assert_eq!(v["object"], "chat.completion");
    assert_eq!(v["model"], "mock-model");
    assert_eq!(v["choices"][0]["message"]["role"], "assistant");
    assert_eq!(v["choices"][0]["message"]["content"], "Hello");
    assert_eq!(v["choices"][0]["finish_reason"], "stop");
    assert_eq!(v["usage"]["completion_tokens"], 2);
    assert_eq!(v["usage"]["prompt_tokens_details"]["cached_tokens"], 3);
    assert_eq!(v["usage"]["total_tokens"], v["usage"]["prompt_tokens"].as_u64().unwrap() + 2);

    let r = mock.reqs.lock().unwrap()[0].clone();
    assert_eq!(r.max_tokens, 9, "max_completion_tokens wins");
    assert_eq!((r.min_tokens, r.ignore_eos, r.top_k, r.seed), (1, true, 7, Some(11)));
    assert!((r.temperature - 0.5).abs() < 1e-6 && (r.top_p - 0.9).abs() < 1e-6);
    assert_eq!(r.stop, vec!["END", "STOP"]);
    let (msgs, opts) = mock.templated.lock().unwrap()[0].clone();
    assert_eq!(msgs[1]["content"], "hi there", "content parts flattened");
    assert_eq!(opts.enable_thinking, Some(false));
    assert_eq!(opts.extra.get("foo"), Some(&json!(1)));
    assert!(opts.add_generation_prompt);
}

#[tokio::test]
async fn chat_stream_with_usage() {
    let (app, _) = app();
    let (st, ct, body) = call(
        &app,
        "POST",
        "/v1/chat/completions",
        Some(json!({"messages": [{"role": "user", "content": "hi"}], "stream": true,
                    "stream_options": {"include_usage": true}})),
    )
    .await;
    assert_eq!(st, StatusCode::OK);
    assert!(ct.starts_with("text/event-stream"), "{ct}");
    let data = sse_data(&body);
    assert_eq!(data.last().unwrap(), "[DONE]");
    let chunks: Vec<Value> = data[..data.len() - 1].iter().map(|d| serde_json::from_str(d).unwrap()).collect();
    assert_eq!(chunks[0]["choices"][0]["delta"]["role"], "assistant");
    let text: String = chunks.iter().filter_map(|c| c["choices"][0]["delta"]["content"].as_str()).collect();
    assert_eq!(text, "Hello");
    let fin = &chunks[chunks.len() - 2];
    assert_eq!(fin["choices"][0]["finish_reason"], "stop");
    let usage = chunks.last().unwrap();
    assert_eq!(usage["choices"], json!([]));
    assert_eq!(usage["usage"]["completion_tokens"], 2);
    assert_eq!(usage["usage"]["prompt_tokens_details"]["cached_tokens"], 3);
    // every chunk shares the id
    let id = &chunks[0]["id"];
    assert!(chunks.iter().all(|c| &c["id"] == id));
    assert!(chunks[0]["usage"].is_null());
}


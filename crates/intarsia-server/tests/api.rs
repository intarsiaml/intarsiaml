/// Concatenated `content` deltas and the tool-call deltas of an OpenAI chat stream, plus its finish reason.
fn chat_stream_parts(body: &str) -> (String, Vec<Value>, String) {
    let (mut text, mut calls, mut finish) = (String::new(), vec![], String::new());
    for d in sse_data(body) {
        if d == "[DONE]" {
            continue;
        }
        let v: Value = serde_json::from_str(&d).unwrap();
        let Some(c) = v["choices"].get(0) else { continue };
        if let Some(t) = c["delta"]["content"].as_str() {
            text.push_str(t);
        }
        if let Some(tc) = c["delta"]["tool_calls"].as_array() {
            calls.extend(tc.iter().cloned());
        }
        if let Some(f) = c["finish_reason"].as_str() {
            finish = f.to_string();
        }
    }
    (text, calls, finish)
}

#[tokio::test]
async fn response_format_json_schema_constrains_chat_and_completions() {
    // the mock model wants prose (the GSM8K failure mode); the constraint makes it JSON that fits the schema
    let (app, mock) = structured("The answer is 42.");
    let (st, _, body) = call(
        &app,
        "POST",
        "/v1/chat/completions",
        Some(json!({"messages": user("q"), "response_format": json_schema_rf(), "max_tokens": 100})),
    )
    .await;
    assert_eq!(st, StatusCode::OK, "{body}");
    let v: Value = serde_json::from_str(&body).unwrap();
    let content = v["choices"][0]["message"]["content"].as_str().unwrap();
    let out: Value = serde_json::from_str(content).unwrap_or_else(|e| panic!("{e}: {content:?}"));
    assert!(out["answer"].is_i64() && out.as_object().unwrap().len() == 1, "{content}");
    assert_eq!(v["choices"][0]["finish_reason"], "stop");
    assert!(mock.reqs.lock().unwrap()[0].constraint.is_some());

    // a model that already says the right thing is left alone
    let (app, _) = structured(r#"{"answer": 18}"#);
    let (_, _, body) = call(
        &app,
        "POST",
        "/v1/chat/completions",
        Some(json!({"messages": user("q"), "response_format": json_schema_rf(), "stream": true})),
    )
    .await;
    let (text, calls, finish) = chat_stream_parts(&body);
    assert_eq!((text.as_str(), calls.len(), finish.as_str()), (r#"{"answer": 18}"#, 0, "stop"));

    // /v1/completions takes response_format too
    let (app, _) = structured("hello");
    for stream in [false, true] {
        let (st, _, body) = call(
            &app,
            "POST",
            "/v1/completions",
            Some(json!({"prompt": "q", "response_format": {"type": "json_object"}, "stream": stream})),
        )
        .await;
        assert_eq!(st, StatusCode::OK, "{body}");
        let text = if stream {
            sse_data(&body)
                .iter()
                .filter(|d| *d != "[DONE]")
                .filter_map(|d| serde_json::from_str::<Value>(d).ok())
                .filter_map(|v| v["choices"].get(0).and_then(|c| c["text"].as_str()).map(String::from))
                .collect::<String>()
        } else {
            serde_json::from_str::<Value>(&body).unwrap()["choices"][0]["text"].as_str().unwrap().to_string()
        };
        assert!(serde_json::from_str::<Value>(&text).unwrap().is_object(), "{text:?}");
    }
    // response_format text and null are no constraint
    let (app, mock) = structured("");
    for rf in [json!({"type": "text"}), Value::Null] {
        call(&app, "POST", "/v1/chat/completions", Some(json!({"messages": user("q"), "response_format": rf}))).await;
    }
    assert!(mock.reqs.lock().unwrap().iter().all(|r| r.constraint.is_none()));
}


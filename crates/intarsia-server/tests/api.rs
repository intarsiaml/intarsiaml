    assert_eq!(v["stop_reason"], "tool_use", "{resp}");
    let blocks = v["content"].as_array().unwrap();
    let tu = blocks.iter().find(|b| b["type"] == "tool_use").expect("a tool_use block");
    assert_eq!(tu["name"], "get_weather");
    assert!(tu["id"].as_str().unwrap().starts_with("toolu_"));
    assert!(tu["input"]["city"].is_string(), "{resp}");

    let mut b = body;
    b["stream"] = json!(true);
    let (_, _, resp) = call(&app, "POST", "/v1/messages", Some(b)).await;
    let ev = sse_events(&resp);
    let names: Vec<&str> = ev.iter().map(|(n, _)| n.as_str()).collect();
    assert_eq!(names.first(), Some(&"message_start"));
    assert_eq!(names.last(), Some(&"message_stop"));
    let start =
        ev.iter().find(|(n, v)| n == "content_block_start" && v["content_block"]["type"] == "tool_use").unwrap();
    let i = start.1["index"].clone();
    let partial: String = ev
        .iter()
        .filter(|(n, v)| n == "content_block_delta" && v["index"] == i && v["delta"]["type"] == "input_json_delta")
        .map(|(_, v)| v["delta"]["partial_json"].as_str().unwrap().to_string())
        .collect();
    assert!(serde_json::from_str::<Value>(&partial).unwrap()["city"].is_string());
    let delta = ev.iter().find(|(n, _)| n == "message_delta").unwrap();
    assert_eq!(delta.1["delta"]["stop_reason"], "tool_use");
    // every started block is stopped, indices in order
    let starts: Vec<&Value> = ev.iter().filter(|(n, _)| n == "content_block_start").map(|(_, v)| &v["index"]).collect();
    let stops: Vec<&Value> = ev.iter().filter(|(n, _)| n == "content_block_stop").map(|(_, v)| &v["index"]).collect();

#!/usr/bin/env bash
# Lane vat: per-category speed window for the 27B at tp=1 (card 0; TP=2: both cards, --tp 2), driven FROM THE MAC (localeval lives here), one fleetq job that
# holds both R9700s and takes radiance down (after scripts/tp2-hip/speed-window.sh):
#   fleetq run --host tatooine-r9700,tatooine-r9700-2 --takes-down radiance --quiet gpu,cpu --expect 50 --mem 30 \
#     --label "vat cat" -- env W=w5 scripts/vat/cat-window.sh
# Arms (ARMS, default "off mtp2 dfl7"): a fresh `serve --max-batch 1` per arm, then `localeval quality --judge none` over every file
# of scripts/vat/cats/ (categories-rcp recall/code/prose and the held-out prose/chat/code/recall, one call per file so the server's
# speculation counters can be read per category), max 512 tokens forced (ignore_eos + min_tokens through a lane-local
# LOCALEVAL_TARGETS file). Rounds (ROUNDS, default 1) alternate the arm order. PROBE=1 first runs tests/dflash2_real.rs on card 0.
# Radiance is restored by guard.sh on tatooine when this script ends or dies.
# R0 (default 1): number of the first round (a second window continues the alternation: R0=3). SOAK=N with SOAK_ARMS (default
# "mtp2"): after an arm's files in its first round, N greedy chat requests (256 forced tokens, two prompts alternating) and the
# sha256 of each answer: run-to-run identity at this arm's settings (graph lock on, the default); SOAK_REF=2 sends the same two
# prompts twice to every other arm, so the soak answers can also be compared with the off arm's.
# Do not edit this file during a window: bash reads it as it goes (w5 ended with a syntax error after an edit).
set -uo pipefail
: "${FLEETQ_JOB:?run under fleetq run}" "${W:?W=<window>}"
TP=${TP:-1}; GPUS=0; TPA=""; [[ $TP == 2 ]] && { GPUS=0,1; TPA="--tp 2 --devices 0,1"; }
TREE=${TREE:-dev}; ROUNDS=${ROUNDS:-1}; ARMS=${ARMS:-"off mtp2 dfl7"}; GEN=${GEN:-512}; CAP=${CAP:-2700}; PORT=8095
M27=/models/radiance/hf-cache/hub/models--amd--Qwen3.8-27B-Quark-AWQ-MXFP4/snapshots/5233554c5fa56afda40150556b95573c2d7d29c0
DRAFT=/models/tensorfold/Qwen3.8-27B-DFlash2
IMG=intarsia-hip-dev:rocm7.2.4-rust1.90.0
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; REPO="$(cd "$HERE/../.." && pwd)"
OUT=$REPO/docs/results/2026-10-28-vat-verify-attn-rows/raw/$W; mkdir -p "$OUT"
T0=$(date +%s); left() { echo $(( CAP - ($(date +%s) - T0) )); }
say() { echo "$(date +%T) $*" | tee -a "$OUT/steps.log"; }
SSH="ssh -o BatchMode=yes tatooine"
[[ -n ${ARMSEQ:-} ]] && ROUNDS=$(( $(echo "$ARMSEQ" | tr -cd ";" | wc -c) + 1 ))
# DRY=1 (a cpu slot, radiance up): print every arm's serve command, the rounds, soak and pre-stage settings, and exit
if [[ ${DRY:-0} == 1 ]]; then
  R0=${R0:-1}; for r in $(seq "$R0" $(( R0 + ROUNDS - 1 ))); do
    order="$ARMS"; (( r % 2 == 0 )) && order=$(echo $ARMS | awk '{for (i=NF;i>=1;i--) printf "%s ", $i}')
    # ARMSEQ (lane vat): explicit arm order per round, rounds separated by ";" (overrides ARMS and ROUNDS), e.g. "mtp2 mtp3;mtp3 off mtp2"
    [[ -n ${ARMSEQ:-} ]] && order=$(echo "$ARMSEQ" | cut -d';' -f$(( r - R0 + 1 )))
    for arm in $order; do
      echo "DRY round $r arm $arm: HIP_VISIBLE_DEVICES=$GPUS serve --backend hip --model $M27 $spec $TPA --max-batch 1 --mem-budget 29 --max-seq 8192, files: $(ls "$HERE"/../dfh/cats/*.jsonl | xargs -n1 basename | tr '\n' ' ')"
    done
  done
  echo "DRY PRE=${PRE:-} IDARMS=${IDARMS:-} TPS=${TPS:-} IDNAMES=${IDNAMES:-} VERIFY8=${VERIFY8:-0} SOAK=${SOAK:-0} SOAK_ARMS=${SOAK_ARMS:-mtp2} SOAK_REF=${SOAK_REF:-2} CAP=$CAP GEN=$GEN"
  exit 0
fi
FIFO=$(mktemp -u "$REPO/target/vatguard.XXXXXX"); mkfifo "$FIFO"
$SSH 'mkdir -p ~/intarsiaml-vat/.vat' < /dev/null; scp -q "$HERE/guard.sh" "$HERE/lib.sh" "$HERE/stages-ids.sh" "$HERE/stages-phase.sh" "$HERE/stages-gates.sh" "$HERE/stages-final.sh" tatooine:intarsiaml-vat/.vat/
$SSH 'bash ~/intarsiaml-vat/.vat/guard.sh' > "$OUT/guard.log" 2>&1 < "$FIFO" &
GUARD=$!
exec 9> "$FIFO"
for i in $(seq 1 30); do grep -q "radiance stopped" "$OUT/guard.log" 2>/dev/null && break; sleep 1; done
say "guard: $(grep -h 'radiance stopped' "$OUT/guard.log")"
cleanup() { $SSH 'docker rm -f vat-serve' >/dev/null 2>&1 < /dev/null; exec 9>&-; wait $GUARD; rm -f "$FIFO"; say "guard: $(grep -h 'radiance answers\|DID NOT' "$OUT/guard.log")"
  start=$(grep -m1 'radiance stopped' "$OUT/guard.log" | grep -oE '[0-9]{2}:[0-9]{2}:[0-9]{2}'); back=$(grep -m1 'radiance answers' "$OUT/guard.log" | grep -oE '[0-9]{2}:[0-9]{2}:[0-9]{2}' | head -1)
  echo "$(date +%F) fleetq #$FLEETQ_JOB $W radiance stopped $start answers ${back:-NEVER} (guard.log in raw/$W)" >> "$OUT/../downtime.log"; }
trap cleanup EXIT

# PRE=ids: first the 27B ids gate (scripts/vat/stages-ids.sh ON tatooine, IDARMS / TPS passed through, at most PRE_CAP s), its
# output fetched into raw/<W>/ids/
if [[ ${PRE:-} == ids || ${PRE:-} == phase || ${PRE:-} == final ]]; then
  say "pre: ids gate (arms ${IDARMS:-dfl mtp2}, ${TPS:-tp1 tp2}, cap ${PRE_CAP:-1200} s)"
  $SSH "rm -rf ~/intarsiaml-vat/.vat/out/$W-ids; mkdir -p ~/intarsiaml-vat/.vat/out/$W-ids; IDARMS='${IDARMS:-dfl mtp2}' TPS='${TPS:-tp1 tp2}' IDNAMES='${IDNAMES:-}' VERIFY8='${VERIFY8:-0}' timeout ${PRE_CAP:-1200} bash ~/intarsiaml-vat/.vat/stages-${PRE}.sh ~/intarsiaml-vat/.vat/out/$W-ids" \
    < /dev/null > "$OUT/ids-pre.log" 2>&1
  say "pre: ids exit $?"
  mkdir -p "$OUT/ids"; scp -q "tatooine:intarsiaml-vat/.vat/out/$W-ids/*" "$OUT/ids/" 2>/dev/null
  say "pre: $(grep -h 'ids summary' "$OUT/ids/steps.log" | cut -c10- | tr '\n' '|')"
fi
if [[ ${PROBE:-0} == 1 ]]; then
  say "probe: tests/dflash2_real.rs on card 0"
  $SSH "export O=\$HOME/intarsiaml-vat/.vat/out/$W; mkdir -p \$O; source ~/intarsiaml-vat/.vat/lib.sh; E='INTARSIA_DFLASH2_TARGET=$M27 INTARSIA_DFLASH2_DRAFT=$DRAFT INTARSIA_DFLASH2_LEN=3000' mtest $TREE probe27 0 600 --test dflash2_real -- --nocapture; cat \$O/mtest-probe27.log" < /dev/null > "$OUT/mtest-probe27.log" 2>&1
  say "probe: $(grep -aE 'PROBE_TIME|PROBE_DRAFT_PROFILE' "$OUT/mtest-probe27.log" | tr '\n' '|')"
fi

serve() { # serve <arm>
  local arm=$1 spec ENVX="" base=$1
  # lane vat: arm "<arm>-old" = the same arm with the lane's new paths off (OLDENV, default the verify attention rows knob)
  if [[ $arm == *-old ]]; then base=${arm%-old}; ENVX="${OLDENV:--e INTARSIA_HIP_VERIFY_ATTN_ROWS=0}"; fi
  case $base in
    off) spec="--spec off" ;;
    mtp2) spec="--spec mtp --spec-k 2" ;;
    mtp*) spec="--spec mtp --spec-k ${base#mtp}" ;;
    dfl*) spec="--spec dflash --spec-draft $DRAFT --spec-k ${base#dfl}" ;;
  esac
  RECIPE="HIP_VISIBLE_DEVICES=$GPUS vat-intarsia serve --backend hip --model 27B $spec $TPA --max-batch 1 --profile-every 0 --mem-budget 29 --max-seq 8192 (tree $TREE, docker $IMG, lane vat)"
  $SSH "docker rm -f vat-serve >/dev/null 2>&1; docker run -d --name vat-serve --network host --device /dev/kfd --device /dev/dri \
    --group-add \$(stat -c %g /dev/kfd) --group-add \$(stat -c %g /dev/dri/renderD128) --group-add video --ipc host \
    --security-opt seccomp=unconfined --user \$(id -u):\$(id -g) -e HOME=/tmp -e GPU_MAX_HW_QUEUES=1 -e HIP_VISIBLE_DEVICES=$GPUS $ENVX \
    -v \$HOME/intarsiaml-vat:/work -v /data/models:/models:ro -w /work $IMG /work/vat-intarsia serve --backend hip --model $M27 \
    --served-model-name qwen38-27b-$arm $spec $TPA --max-batch 1 --profile-every 0 --mem-budget 29 --max-seq 8192 --no-supervisor --host 0.0.0.0 --port $PORT" \
    < /dev/null > "$OUT/docker-$arm.id" 2>&1
  for i in $(seq 1 100); do curl -sf -m 3 "http://tatooine:$PORT/health" > /dev/null 2>&1 && return 0; sleep 3; done
  $SSH 'docker logs --tail 40 vat-serve' > "$OUT/serve-fail-$arm.log" 2>&1 < /dev/null; return 1
}
metric() { curl -s -m 5 "http://tatooine:$PORT/metrics" | grep -E '^intarsia_spec_(steps|proposed_tokens|accepted_tokens|costgate_[a-z_]+)_total' | sed 's/{[^}]*}//' | tr '\n' ' '; }

R0=${R0:-1}; SOAK=${SOAK:-0}; SOAK_ARMS=${SOAK_ARMS:-mtp2}; SOAK_REF=${SOAK_REF:-2}
SOAK_P=("Write a long story about a robot who learns to paint." "Explain, step by step, how a hash map handles collisions, with code in Rust.")
soak() { # soak <arm> <n>
  local arm=$1 n=$2 i p h
  for i in $(seq 1 "$n"); do
    p=${SOAK_P[$(( (i - 1) % 2 ))]}
    h=$(curl -s -m 120 "http://tatooine:$PORT/v1/chat/completions" -H 'content-type: application/json' -d "$(python3 -c 'import json,sys; print(json.dumps({"model": sys.argv[1], "messages": [{"role": "user", "content": sys.argv[2]}], "max_tokens": 256, "temperature": 0, "ignore_eos": True, "min_tokens": 256, "chat_template_kwargs": {"enable_thinking": False}}))' "qwen38-27b-$arm" "$p")" |
      python3 -c 'import sys,json,hashlib; d=json.load(sys.stdin); c=d["choices"][0]["message"]["content"]; print(hashlib.sha256(c.encode()).hexdigest()[:16], d["usage"]["completion_tokens"])' 2>&1)
    echo "$arm p$(( (i - 1) % 2 )) rep $i: $h" >> "$OUT/soak.txt"
  done
  say "soak $arm: $n requests, distinct answers per prompt: $(grep "^$arm p0 " "$OUT/soak.txt" | awk '{print $5}' | sort -u | wc -l | tr -d ' ') (p0) $(grep "^$arm p1 " "$OUT/soak.txt" | awk '{print $5}' | sort -u | wc -l | tr -d ' ') (p1)"
}
for r in $(seq "$R0" $(( R0 + ROUNDS - 1 ))); do
  order="$ARMS"; (( r % 2 == 0 )) && order=$(echo $ARMS | awk '{for (i=NF;i>=1;i--) printf "%s ", $i}')
  # ARMSEQ (lane vat): explicit arm order per round, rounds separated by ";" (overrides ARMS and ROUNDS), e.g. "mtp2 mtp3;mtp3 off mtp2"
  [[ -n ${ARMSEQ:-} ]] && order=$(echo "$ARMSEQ" | cut -d';' -f$(( r - R0 + 1 )))
  for arm in $order; do
    if (( $(left) < 600 )); then say "SKIPPED round $r arm $arm (time left $(left)s)"; continue; fi
    say "round $r arm $arm: starting server"
    if ! serve "$arm"; then say "round $r arm $arm: server did not come up"; continue; fi
    printf '[targets.vat-%s]\nurl = "http://tatooine:%s/v1"\nmodel = "qwen38-27b-%s"\nextra_body = { ignore_eos = true, min_tokens = %s }\n' "$arm" "$PORT" "$arm" "$GEN" > "$OUT/targets-$arm.toml"
    for f in "$HERE"/../dfh/cats/*.jsonl; do
      c=$(basename "$f" .jsonl); m0=$(metric)
      ( cd /opt/code/deepeval && LOCALEVAL_TARGETS="$OUT/targets-$arm.toml" uv run localeval quality "vat-$arm" --thinking off --label "vat-$W-$arm-$c-r$r" \
          --recipe "$RECIPE" --dataset "$f" --judge none --max-tokens "$GEN" --wait-idle 60 ) > "$OUT/q-$arm-$c-r$r.log" 2>&1 < /dev/null
      rc=$?; m1=$(metric)
      echo "$arm $c r$r before: $m0" >> "$OUT/spec-metrics.txt"; echo "$arm $c r$r after:  $m1" >> "$OUT/spec-metrics.txt"
      say "round $r arm $arm $c: localeval exit $rc $(grep -aoE 'results/[^ ]+' "$OUT/q-$arm-$c-r$r.log" | tail -1)"
    done
    if [[ -n ${SPEEDSIZES:-} && ${arm%-old} == off ]]; then  # lane vat: plain decode at the given context sizes (the spec-off no-regression gate)
      ( cd /opt/code/deepeval && LOCALEVAL_TARGETS="$OUT/targets-$arm.toml" uv run localeval speed "vat-$arm" --sizes "$SPEEDSIZES" --gen 128 --reps 3 \
          --label "vat-$W-$arm-speed-r$r" --recipe "$RECIPE" --wait-idle 60 ) > "$OUT/speed-$arm-r$r.log" 2>&1 < /dev/null
      say "round $r arm $arm speed $SPEEDSIZES: exit $? $(grep -aoE 'results/[^ ]+' "$OUT/speed-$arm-r$r.log" | tail -1)"
    fi
    if (( SOAK > 0 && r == R0 )); then
      if [[ " $SOAK_ARMS " == *" $arm "* ]]; then soak "$arm" "$SOAK"; elif (( SOAK_REF > 0 )); then soak "$arm" "$SOAK_REF"; fi
    fi
    $SSH 'docker logs vat-serve 2>&1 | grep -aE "speculative|dflash|mtp|graph|error" | tail -12' < /dev/null > "$OUT/serve-$arm-r$r.log" 2>&1
    $SSH 'docker rm -f vat-serve' >/dev/null 2>&1 < /dev/null
  done
done
say "done, time left $(left)s"

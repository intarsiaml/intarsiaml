#!/usr/bin/env bash
# Lane mpf: per-category speed window and soak for the 35B NVFP4 on spark1 (CUDA, tp=1), driven FROM THE MAC (localeval lives here), one
# fleetq job that holds the box quiet (after scripts/dfh/cat-window.sh, ported from tatooine/docker to spark1/ssh):
#   fleetq run --host spark1 --quiet gpu,cpu --mem 50 --expect 70 --label "mpf: speed" -- env W=s1 scripts/mpf/window.sh
# Arms (ARMS, default "off mtp2 mtp3"): a fresh `serve --max-batch 1` per arm (off: --spec off; mtpK: --spec mtp --spec-k K; auto: no --spec,
# i.e. the recipe default), then `localeval quality --judge none` over every file of scripts/dfh/cats/ (the 27B lane's categories: held-out
# chat/code/prose/recall and rcp code/prose/recall; CATS=none skips them), max 512 tokens forced (ignore_eos + min_tokens through a
# lane-local LOCALEVAL_TARGETS file). Rounds (ROUNDS, default 3) alternate the arm order. SOAK=N with SOAK_ARMS (default "auto"): after an
# arm's files in its first round, N greedy chat requests (256 forced tokens, two prompts alternating) and the sha256 of each answer;
# SOAK_REF=N sends the same two prompts N times to every other arm so the answers can be compared with spec-off's.
# Do not edit this file during a window: bash reads it as it goes.
set -uo pipefail
: "${FLEETQ_JOB:?run under fleetq run}" "${W:?W=<window>}"
ROUNDS=${ROUNDS:-3}; ARMS=${ARMS:-"off mtp2 mtp3"}; GEN=${GEN:-512}; CAP=${CAP:-4800}; PORT=${PORT:-8095}
SOAK=${SOAK:-0}; SOAK_ARMS=${SOAK_ARMS:-auto}; SOAK_REF=${SOAK_REF:-2}; R0=${R0:-1}
BIN=${BIN:-'~/intarsiaml-mpf/target-dev/release/intarsia'}
M35='$(ls -d /home/nvidia/.cache/huggingface/hub/models--nvidia--Qwen3.6-35B-A3B-NVFP4/snapshots/* | head -1)'
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; REPO="$(cd "$HERE/../.." && pwd)"
OUT=$REPO/docs/results/2026-10-27-mpf-macro-prefill-mtp/raw/$W; mkdir -p "$OUT"
T0=$(date +%s); left() { echo $(( CAP - ($(date +%s) - T0) )); }
say() { echo "$(date +%T) $*" | tee -a "$OUT/steps.log"; }
SSH="ssh -o BatchMode=yes spark1"
PID='~/intarsiaml-mpf/out/serve.pid'; LOG='~/intarsiaml-mpf/out/serve'
specflag() { case $1 in off) echo "--spec off" ;; auto) echo "" ;; mtp*) echo "--spec mtp --spec-k ${1#mtp}" ;; esac; }
stop() { $SSH "if [ -f $PID ]; then p=\$(cat $PID); kill \$p 2>/dev/null; for _ in \$(seq 1 60); do kill -0 \$p 2>/dev/null || break; sleep 1; done; kill -9 \$p 2>/dev/null; rm -f $PID; fi" < /dev/null; }
trap stop EXIT INT TERM
if [[ ${DRY:-0} == 1 ]]; then
  for arm in $ARMS; do echo "DRY arm $arm: $BIN serve --backend cuda --model $M35 --model-id qwen36-35b-$arm $(specflag "$arm") --max-batch 1 --profile-every 0 --mem-budget 40 --max-seq 8192, files: $(ls "$HERE"/../dfh/cats/*.jsonl | xargs -n1 basename | tr '\n' ' ')"; done
  echo "DRY ROUNDS=$ROUNDS SOAK=$SOAK SOAK_ARMS=$SOAK_ARMS SOAK_REF=$SOAK_REF CATS=${CATS:-all} CAP=$CAP"; exit 0
fi
serve() { # serve <arm>
  local arm=$1 spec; spec=$(specflag "$arm")
  RECIPE="intarsia serve --backend cuda --model Qwen3.6-35B-A3B-NVFP4 $spec --max-batch 1 --profile-every 0 --mem-budget 40 --max-seq 8192 (spark1, lane cmtp)"
  $SSH "mkdir -p ~/intarsiaml-mpf/out; nohup $BIN serve --backend cuda --model $M35 --model-id qwen36-35b-$arm $spec --max-batch 1 --profile-every 0 \
    --mem-budget 40 --max-seq 8192 --no-supervisor --host 0.0.0.0 --port $PORT > $LOG-$arm.log 2>&1 < /dev/null & echo \$! > $PID" < /dev/null
  for i in $(seq 1 100); do curl -sf -m 3 "http://spark-4e77:$PORT/health" > /dev/null 2>&1 && return 0; sleep 3; done
  $SSH "tail -20 $LOG-$arm.log" < /dev/null > "$OUT/serve-fail-$arm.log" 2>&1; return 1
}
metric() { curl -s -m 5 "http://spark-4e77:$PORT/metrics" | grep -E '^intarsia_spec_(steps|proposed_tokens|accepted_tokens|costgate_[a-z_]+)_total' | sed 's/{[^}]*}//' | tr '\n' ' '; }
# prompt 1 is a ~3k-token document (more than one 2048-row prefill chunk: the macro prefill pass runs) with a question
SOAK_P=("Write a long story about a robot who learns to paint." "$(cat "$HERE/ids-prompts/4k-1.txt")")
soak() { # soak <arm> <n>
  local arm=$1 n=$2 i p h
  for i in $(seq 1 "$n"); do
    p=${SOAK_P[$(( (i - 1) % 2 ))]}
    h=$(curl -s -m 120 "http://spark-4e77:$PORT/v1/chat/completions" -H 'content-type: application/json' -d "$(python3 -c 'import json,sys; print(json.dumps({"model": sys.argv[1], "messages": [{"role": "user", "content": sys.argv[2]}], "max_tokens": 256, "temperature": 0, "ignore_eos": True, "min_tokens": 256, "chat_template_kwargs": {"enable_thinking": False}}))' "qwen36-35b-$arm" "$p")" |
      python3 -c 'import sys,json,hashlib; d=json.load(sys.stdin); c=d["choices"][0]["message"]["content"]; print(hashlib.sha256(c.encode()).hexdigest()[:16], d["usage"]["completion_tokens"])' 2>&1)
    echo "$arm p$(( (i - 1) % 2 )) rep $i: $h" >> "$OUT/soak.txt"
  done
  say "soak $arm: $n requests, distinct answers per prompt: $(grep "^$arm p0 " "$OUT/soak.txt" | awk '{print $5}' | sort -u | wc -l | tr -d ' ') (p0) $(grep "^$arm p1 " "$OUT/soak.txt" | awk '{print $5}' | sort -u | wc -l | tr -d ' ') (p1)"
}
for r in $(seq "$R0" $(( R0 + ROUNDS - 1 ))); do
  order="$ARMS"; (( r % 2 == 0 )) && order=$(echo $ARMS | awk '{for (i=NF;i>=1;i--) printf "%s ", $i}')
  for arm in $order; do
    if (( $(left) < 600 )); then say "SKIPPED round $r arm $arm (time left $(left)s)"; continue; fi
    say "round $r arm $arm: starting server ($(specflag "$arm"))"
    if ! serve "$arm"; then say "round $r arm $arm: server did not come up"; stop; continue; fi
    say "round $r arm $arm: $($SSH "grep -aE 'default of recipe|spec mtp|speculat' $LOG-$arm.log | head -3 | cut -c1-200" < /dev/null | tr '\n' '|')"
    printf '[targets.cmtp-%s]\nurl = "http://spark-4e77:%s/v1"\nmodel = "qwen36-35b-%s"\nextra_body = { ignore_eos = true, min_tokens = %s }\n' "$arm" "$PORT" "$arm" "$GEN" > "$OUT/targets-$arm.toml"
    if [[ ${CATS:-all} != none ]]; then
      for f in "$HERE"/../dfh/cats/*.jsonl; do
        c=$(basename "$f" .jsonl); m0=$(metric)
        ( cd /opt/code/deepeval && LOCALEVAL_TARGETS="$OUT/targets-$arm.toml" uv run localeval quality "cmtp-$arm" --thinking off --label "cmtp-$W-$arm-$c-r$r" \
            --recipe "$RECIPE" --dataset "$f" --judge none --max-tokens "$GEN" --wait-idle 60 ) > "$OUT/q-$arm-$c-r$r.log" 2>&1 < /dev/null
        rc=$?; m1=$(metric)
        echo "$arm $c r$r before: $m0" >> "$OUT/spec-metrics.txt"; echo "$arm $c r$r after:  $m1" >> "$OUT/spec-metrics.txt"
        say "round $r arm $arm $c: localeval exit $rc $(grep -aoE 'results/[^ ]+' "$OUT/q-$arm-$c-r$r.log" | tail -1)"
      done
    fi
    if (( SOAK > 0 && r == R0 )); then
      if [[ " $SOAK_ARMS " == *" $arm "* ]]; then soak "$arm" "$SOAK"; elif (( SOAK_REF > 0 )); then soak "$arm" "$SOAK_REF"; fi
    fi
    $SSH "grep -aE 'speculative|mtp|graph|error' $LOG-$arm.log | tail -12" < /dev/null > "$OUT/serve-$arm-r$r.log" 2>&1
    stop
  done
done
say "done, time left $(left)s"
